export const ARCHETYPES: Archetype[] = RAW.map((a) => ({
  ...a,
  // só a principal aparece no site (out/2026); a secundária vale pros filtros (FAMILIES em home.ts)
  fam: FAMILIAS_BY_SLUG[a.familias[0]].nome,
}))

export const ARCHETYPES_BY_ID: Record<string, Archetype> = Object.fromEntries(
  ARCHETYPES.map((a) => [a.id, a]),
)

export function getArchetype(id: string): Archetype | undefined {
  return ARCHETYPES_BY_ID[id]
}

export function segmentPool(seg: 'F' | 'M' | 'todos'): Archetype[] {
  if (seg === 'F') return ARCHETYPES.filter((a) => a.seg === 'F')
  if (seg === 'M') return ARCHETYPES.filter((a) => a.seg === 'M' || a.seg === 'U')
  return ARCHETYPES
}

