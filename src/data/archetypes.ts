export const ARCHETYPES: Archetype[] = RAW.map((a) => ({
  ...a,
  // só a principal aparece no site (out/2026); a secundária vale pros filtros (FAMILIES em home.ts)
  fam: FAMILIAS_BY_SLUG[a.familias[0]].nome,
}))

export const ARCHETYPES_BY_ID: Record<string, Archetype> = Object.fromEntries(
  ARCHETYPES.map((a) => [a.id, a]),
)

export function getArchetype(id: string): Archetype | undefined {
  return Object.hasOwn(ARCHETYPES_BY_ID, id) ? ARCHETYPES_BY_ID[id] : undefined
}

/** Prefixo da PDP. Endereços antigos (/loja/:id, /arquetipos/:id) redirecionam (vercel.json + App.tsx). */
export const PRODUCT_BASE = '/body-splash'

/** URL definitiva do produto — todo link pra PDP sai daqui, nunca montado à mão */
export const productPath = (a: Pick<Archetype, 'slug'>) => `${PRODUCT_BASE}/${a.slug}`

/** "Body Splash Premium Zeus Stormbreak" — nome comercial completo, pra textos alternativos das fotos */
export const produtoNome = (a: Pick<Archetype, 'tipo' | 'nome' | 'sobrenome'>) =>
  `${a.tipo} ${a.nome} ${a.sobrenome ?? ''}`.trim()

export function getArchetypeBySlug(slug: string): Archetype | undefined {
  return ARCHETYPES.find((a) => a.slug === slug)
}

export function segmentPool(seg: 'F' | 'M' | 'todos'): Archetype[] {
  if (seg === 'F') return ARCHETYPES.filter((a) => a.seg === 'F')
  if (seg === 'M') return ARCHETYPES.filter((a) => a.seg === 'M' || a.seg === 'U')
  return ARCHETYPES
}

